# ====== configuration ======
BITS_PER_SYMBOL = 3       # values 0..7
OUTPUT_DIR = r"RTL\Pacman\maps_mif"

# which characters are allowed in the map (extend as you add tiles)
ALLOWED = set("0123456789")  # allows up to '9' if you later bump BITS_PER_SYMBOL

def map_to_mif(map_str: str, out_path: str, bits: int = BITS_PER_SYMBOL):
    # normalize lines & validate rectangle
    lines = [ln.strip() for ln in map_str.splitlines() if ln.strip()]
    if not lines:
        raise ValueError("Empty map.")
    width = len(lines[0])
    if any(len(ln) != width for ln in lines):
        raise ValueError("Map rows are not equal length.")
    height = len(lines)
    depth = width * height

    # convert chars to integers row-major
    vals = []
    for r, ln in enumerate(lines):
        for c, ch in enumerate(ln):
            if ch not in ALLOWED:
                raise ValueError(f"Illegal symbol '{ch}' at row {r}, col {c}")
            v = int(ch)
            if v >= (1 << bits):
                raise ValueError(
                    f"Value {v} at row {r}, col {c} requires more than {bits} bits"
                )
            vals.append(v)

    # header
    addr_hex_width = max(1, math.ceil(math.log2(max(1, depth)) / 4))
    with open(out_path, "w") as f:
        f.write(f"DEPTH = {depth};\n")
        f.write(f"WIDTH = {bits};\n")
        f.write("ADDRESS_RADIX = HEX;\n")
        f.write("DATA_RADIX = HEX;\n")
        f.write("\nCONTENT BEGIN\n")
        for addr, v in enumerate(vals):
            f.write(f"  {addr:0{addr_hex_width}X} : {v:X};\n")
        f.write("END;\n")

    # helpful printouts for Quartus params
    widthad_a = math.ceil(math.log2(depth))
    print(
        f"Wrote {out_path}  |  size = {width}x{height}  "
        f"DEPTH={depth}  WIDTH={bits}  -> use widthad_a={widthad_a}"
    )

maps = {
    "map1": map1_str,
    "map2": map2_str,
    "map3": map3_str,
    "map4": map4_str,
    "original": original_map_str,
}

os.makedirs(OUTPUT_DIR, exist_ok=True)
for name, data in maps.items():
    out = os.path.join(OUTPUT_DIR, f"{name}.mif")
    map_to_mif(data, out, BITS_PER_SYMBOL)