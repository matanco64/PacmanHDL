	64'b0111110000001111110000000111111110000111111000001111110000011111,
	64'b0111110000001111110000000111111110000111111000001111110000001110,
	64'b0111110000001111111110000011111110000111111111001111110000000000,
	64'b0111110000001111111110000011111100000111111111001111110000000000,
	64'b0111110000001111110000000011111100000111111000001111110000000000,
	64'b0111110000001111110000000001111100000111111000001111110000001110,
	64'b0111111111001111111110000001111000000111111111001111111110011111,
	64'b0111111111001111111110000001111000000111111111001111111110011111,
	64'b0111111111001111111110000001111000000111111111001111111110001110};




// module (ff) to get the pixel color from the array 	 
// The lookup is a reset-free registered read so it maps to block RAM; the
// async reset only clears the "inside" flag, which gives the same output as
// resetting drawingRequest directly.

logic glyph [0:2047];  // {text, y, x}
initial begin
	for (int y = 0; y < 16; y++)
		for (int x = 0; x < 64; x++) begin
			glyph[{1'b0, y[3:0], x[5:0]}] = score[y][x];
			glyph[{1'b1, y[3:0], x[5:0]}] = level[y][x];
		end
end

logic glyphPixel, insideQ;

always_ff@(posedge clk)
	glyphPixel <= glyph[{text, offsetY[3:0], offsetX[5:0]}];

always_ff@(posedge clk or negedge resetN)
begin
	if(!resetN)
		insideQ <= 1'b0;
	else
		insideQ <= InsideRectangle && offsetX < 64 && offsetY < 16;
end

assign drawingRequest = insideQ && glyphPixel;

assign RGBout = digit_color ; // this is a fixed color 

endmodule


